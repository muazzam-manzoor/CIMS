type LanguageContextValue = {
  lang: Language;
  setLang: (language: Language) => void;
  t: (text: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);
let activeLanguage: Language = "en";
const languageListeners = new Set<() => void>();

function subscribeToLanguage(listener: () => void) {
  languageListeners.add(listener);
  return () => languageListeners.delete(listener);
}

function getLanguageSnapshot() {
  return activeLanguage;
}

function getServerLanguageSnapshot(): Language {
  return "en";
}

function setStoredLanguage(language: Language) {
  activeLanguage = language;
  setFormatLocale(language);
  localStorage.setItem("lang", language);
  languageListeners.forEach((listener) => listener());
}

export function translateUI(text: string) {
  if (activeLanguage !== "ja") return text;
  const translation = japanese[text];
  if (translation) return translation;

  const patterns: [RegExp, (match: RegExpMatchArray) => string][] = [
    [
      /^(January|February|March|April|May|June|July|August|September|October|November|December) (\d{4})$/,
      (match) =>
        `${[
          "January",
          "February",
          "March",
          "April",
          "May",
          "June",
          "July",
          "August",
          "September",
          "October",
          "November",
          "December",
        ].indexOf(match[1]) + 1}月 ${match[2]}年`,
    ],
    [/^You owe (.+)$/, (match) => `${match[1]}への未払い`],
    [/^(.+) owes you$/, (match) => `${match[1]}からの未回収額`],
    [
      /^Sold (\d+) days? ago for (.+)$/,
      (match) => `${match[1]}日前に${match[2]}で販売`,
    ],
    [/^Worth (.+)$/, (match) => `${match[1]}相当`],
    [/^After returning (.+)$/, (match) => `${match[1]}返金後`],
    [/^Cost (.+)$/, (match) => `費用 ${match[1]}`],
    [/^(\d+) days?$/, (match) => `${match[1]}日`],
    [
      /^(\d+) sales? (?:was|were) cancelled in this time and (.+) was refunded\. Those cars are not counted as sold\.$/,
      (match) => `この期間に${match[1]}件の販売がキャンセルされ、${match[2]}が返金されました。対象車両は販売台数に含まれません。`,
    ],
    [/^Gave (.+)'s money back$/, (match) => `${match[1]}の資金を返却`],
    [
      /^(.+) took money for personal use$/,
      (match) => `${match[1]}が個人用途で資金を引き出し`,
    ],
    [/^Borrowed money from (.+)$/, (match) => `${match[1]}から借入`],
    [/^Paid back (.+)$/, (match) => `${match[1]}に返済`],
    [/^Lent money to (.+)$/, (match) => `${match[1]}に資金を貸付`],
    [/^(.+) paid back our loan$/, (match) => `${match[1]}が当社への借入金を返済`],
    [
      /^Gave (.+) money to spend on business$/,
      (match) => `${match[1]}に事業用資金を渡した`,
    ],
    [/^(.+) returned unused cash$/, (match) => `${match[1]}が未使用の現金を返却`],
    [/^(.+) spent the money on business$/, (match) => `${match[1]}が資金を事業に使用`],
  ];

  for (const [pattern, render] of patterns) {
    const match = text.match(pattern);
    if (match) return render(match);
  }
  return text;
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const lang = useSyncExternalStore(
    subscribeToLanguage,
    getLanguageSnapshot,
    getServerLanguageSnapshot,
  );

  useEffect(() => {
    const saved = localStorage.getItem("lang");
    if (saved === "en") setStoredLanguage("en");
    else if (saved === "ja") setStoredLanguage("ja");
  }, []);

  useEffect(() => {
    setFormatLocale(lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      lang,
      setLang: setStoredLanguage,
      t: (text) => (lang === "ja" ? japanese[text] ?? text : text),
    }),
    [lang],
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLang() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLang must be used inside LanguageProvider");
  }
  return context;
}
